import pytest
from click.testing import CliRunner, Result

from harness_builder.cli import main as cli_main
from harness_builder.config import Settings
from harness_builder.core.builder import HarnessBuilder
from harness_builder.core.types import Rule, RunResult, ToolCall
from harness_builder.executor.fake import FakeExecutor
from harness_builder.executor.models import ExecResult
from harness_builder.llm.fake import FakeLLMClient
from harness_builder.llm.types import LLMResponse
from harness_builder.skills.extension import SKILL_TOOL_NAMES, install_skills
from harness_builder.skills.hygiene import pending_candidates
from harness_builder.skills.promotion import (
    CANDIDATE_FILE,
    CandidateMeta,
    PromotionError,
    PromotionHook,
    PromotionService,
)
from harness_builder.skills.store import SkillStore
from harness_builder.spec.models import SkillsConfig
from harness_builder.tools.builtin.run_code import run_code

from .support import (  # pyrefly: ignore[missing-import]
    CLI_ENV,
    PROMOTION_MODEL,
    SKILL_NAME,
    SOURCE,
    isolate_cli_env,
    live_names,
    promotion_service,
    skill_reply,
)

pytestmark = pytest.mark.timeout(180)

TASK = "Sum the numbers 1 and 2 and report the total."
CODE = "FINAL(str(sum([1, 2])))"
ALLOW = [Rule(name, "allow") for name in (*SKILL_TOOL_NAMES, "run_code")]


@pytest.fixture
def store(tmp_path: Path) -> SkillStore:
    """An empty skills root (live dir created) under ``tmp_path``."""
    store = SkillStore(tmp_path / "root")
    store.ensure_dirs()
    return store


async def run_once(
    store: SkillStore, hook: PromotionHook, exec_result: ExecResult
) -> RunResult:
    """One run_code call returning ``exec_result``, with promotion installed."""
    call = ToolCall(id="c1", name="run_code", args={"language": "python", "code": CODE})
    llm = FakeLLMClient([LLMResponse(tool_calls=[call])])
    builder = (
        HarnessBuilder("promo", Settings(model="fake/model"))
        .system_prompt("Solve tasks with run_code.")
        .tools(run_code())
        .permissions(ALLOW)
        .llm(llm)
        .executor(FakeExecutor([exec_result]))
        .trace_dir(None)
    )
    install_skills(SkillsConfig(root=str(store.root)), builder, promotion=hook)
    return await builder.build().run(TASK)


VERIFIED = ExecResult(exit_code=0, stdout="", final_set=True, final_value="3")


@pytest.mark.anyio
async def test_on_stop_mode_proposes_a_pending_candidate(store: SkillStore) -> None:
    service = promotion_service(store, skill_reply())
    hook = PromotionHook(service)  # on_stop is the default mode
    result = await run_once(store, hook, VERIFIED)

    assert result.stop.reason == "done" and result.answer == "3"
    [cid] = hook.proposed
    meta = CandidateMeta.model_validate_json(
        (store.candidate_dir(cid) / CANDIDATE_FILE).read_text("utf-8")
    )
    assert meta.name == SKILL_NAME and meta.model == PROMOTION_MODEL.name
    assert meta.source.task == TASK and meta.source.code == CODE
    assert meta.source.final_value == "3"
    skill = store.candidate_dir(cid) / SKILL_NAME
    assert sorted(p.relative_to(skill).as_posix() for p in skill.rglob("*.*")) == [
        "SKILL.md",
        f"scripts/{SKILL_NAME}.py",
        f"tests/test_{SKILL_NAME}.py",
    ]
    assert isinstance(service.llm, FakeLLMClient)
    [request] = service.llm.requests
    assert request.purpose == "promotion" and CODE in request.messages[0].content
    assert live_names(store) == []  # pending only, never live
    assert [p.state for p in pending_candidates(store)] == ["ready"]


@pytest.mark.anyio
@pytest.mark.parametrize(
    "exec_result",
    [
        ExecResult(exit_code=1, final_set=True, final_value="3"),
        ExecResult(exit_code=0, final_set=True, final_value="3", timed_out=True),
        ExecResult(exit_code=0, stdout="3"),  # no FINAL: answer is plain text
    ],
    ids=["nonzero-exit", "timed-out", "no-final"],
)
async def test_unverified_run_proposes_nothing(
    store: SkillStore, exec_result: ExecResult
) -> None:
    service = promotion_service(store)  # an LLM call would exhaust the script
    hook = PromotionHook(service)
    await run_once(store, hook, exec_result)
    assert hook.proposed == []
    assert pending_candidates(store) == []


@pytest.mark.anyio
async def test_promotion_failure_never_changes_the_run(store: SkillStore) -> None:
    hook = PromotionHook(promotion_service(store, "this is not JSON"))
    result = await run_once(store, hook, VERIFIED)
    assert result.stop.reason == "done" and result.answer == "3"
    assert hook.proposed == []
    # source.json was written before the LLM failed: the candidate is
    # deferred and can be retried with `harness skills propose`.
    assert [p.state for p in pending_candidates(store)] == ["deferred"]
    assert live_names(store) == []


@pytest.mark.anyio
async def test_deferred_mode_makes_no_llm_call(store: SkillStore) -> None:
    service = promotion_service(store)
    hook = PromotionHook(service, mode="deferred")
    await run_once(store, hook, VERIFIED)
    [cid] = hook.proposed
    assert isinstance(service.llm, FakeLLMClient) and service.llm.requests == []
    assert [(p.cid, p.state) for p in pending_candidates(store)] == [(cid, "deferred")]


@pytest.mark.anyio
async def test_propose_deferred_then_twice_is_refused(store: SkillStore) -> None:
    service = promotion_service(store, skill_reply(), skill_reply())
    cid = service.write_source(SOURCE)
    assert await service.propose_deferred(cid) == cid
    with pytest.raises(PromotionError, match="already generated"):
        await service.propose_deferred(cid)


# --- CLI: harness skills propose ----------------------------------------------


@pytest.fixture
def cli(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Empty cwd and no ``HARNESS_*``/``OPENROUTER_*`` variables (no model)."""
    monkeypatch.chdir(isolate_cli_env(tmp_path, monkeypatch.delenv))


def fake_llm_file(tmp_path: Path, *replies: str) -> Path:
    """A ``--fake-llm`` JSON list of ``LLMResponse`` objects."""
    path = tmp_path / "promotion-llm.json"
    path.write_text(json.dumps([{"text": reply} for reply in replies]), "utf-8")
    return path


def propose(store: SkillStore, *args: str | Path) -> Result:
    """Run ``harness skills propose <args> --skills-root <root>``."""
    argv = ["skills", "propose", *map(str, args), "--skills-root", str(store.root)]
    return CliRunner().invoke(cli_main.main, argv, env=CLI_ENV)


def deferred(store: SkillStore, count: int) -> list[str]:
    """Write ``count`` deferred candidates; ids sorted (the CLI's order).

    Ids made in the same second differ only in random hex, so creation order
    is not processing order.
    """
    service = PromotionService(store, FakeLLMClient([]), PROMOTION_MODEL)
    return sorted(service.write_source(SOURCE) for _ in range(count))


@pytest.mark.usefixtures("cli")
def test_cli_propose_with_fake_llm_uses_fake_promotion_model(
    store: SkillStore, tmp_path: Path
) -> None:
    [cid] = deferred(store, 1)
    result = propose(store, "--fake-llm", fake_llm_file(tmp_path, skill_reply()))
    assert result.exit_code == 0, result.output
    assert f"{cid}: proposed" in result.output
    meta = CandidateMeta.model_validate_json(
        (store.candidate_dir(cid) / CANDIDATE_FILE).read_text("utf-8")
    )
    assert meta.model == cli_main.FAKE_PROMOTION_MODEL == "fake/promotion"
    assert [(p.cid, p.state) for p in pending_candidates(store)] == [(cid, "ready")]
    assert live_names(store) == []

    again = propose(store, cid, "--fake-llm", fake_llm_file(tmp_path, skill_reply()))
    assert again.exit_code == 1 and "already generated" in again.output


@pytest.mark.usefixtures("cli")
def test_cli_propose_continues_after_a_failure(
    store: SkillStore, tmp_path: Path
) -> None:
    first, second = deferred(store, 2)
    llm = fake_llm_file(tmp_path, "not json", skill_reply())
    result = propose(store, "--fake-llm", llm)
    assert result.exit_code == 1
    assert f"{first}: failed: unparsable promotion output" in result.output
    assert f"{second}: proposed" in result.output
    states = {p.cid: p.state for p in pending_candidates(store)}
    assert states == {first: "deferred", second: "ready"}


@pytest.mark.usefixtures("cli")
def test_cli_propose_without_model_exits_2(store: SkillStore) -> None:
    deferred(store, 1)
    result = propose(store)
    assert result.exit_code == 2 and "HARNESS_MODEL" in result.output


@pytest.mark.usefixtures("cli")
def test_cli_propose_nothing_deferred(store: SkillStore) -> None:
    result = propose(store)
    assert result.exit_code == 0 and "no deferred candidates" in result.output
