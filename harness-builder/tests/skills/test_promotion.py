"""T055: promotion (FR-053) through built harnesses and ``harness skills propose``.

``tests/unit/test_promotion_t052.py`` drives ``PromotionHook`` directly and
T051 covers deferred mode through a harness. Here ``on_stop`` mode runs inside
a real ``build()`` + ``run()``: a verified run leaves one complete pending
candidate (never live), an unverified one leaves nothing, and a promotion
failure never changes the run's result. The CLI part covers deferred
candidates generated by ``skills propose --fake-llm``.
"""

